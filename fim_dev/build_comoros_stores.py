"""Build one scenario store per Comoros municipality (adm3), three islands.

Inputs
  blob + index   the 600 maximum depth rasters of the three island models,
                 quantized to centimetres on the device and deflated
  com_admin3     the municipality boundaries (55 units, EPSG 4326)
  magnitudes     per municipality RainyDay storm totals, area weighted

Outputs, per municipality
  fim_store/Comoros/fim_store_<PCODE>_<Slug>_v1.zarr(.zip)
  fim_config/Comoros_<Slug>.yaml
  fim_config/aoc/Comoros_<PCODE>_<Slug>_aoc.geojson
plus manifest_Comoros.csv and magnitudes_Comoros_per_unit.json
"""
# NOTE ON PATHS: the constants below are the paths of the machine this was
# built on (the delivered Comoros rasters, the com_admin3 shapefile and the
# magnitude table). Point them at your own copies before rerunning. Needs
# numpy, rasterio, geopandas and zarr.
